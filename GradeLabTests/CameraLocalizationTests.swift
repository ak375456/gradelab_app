    func testEveryCameraAndRecordingPaywallStringShipsInEveryLanguage() throws {
        for locale in locales {
            let bundle = try localizedBundle(locale)
            for key in requiredKeys {
                let text = bundle.localizedString(forKey: key, value: "__missing_camera_translation__", table: nil)
                XCTAssertNotEqual(text, "__missing_camera_translation__", "\(locale): \(key)")
                XCTAssertFalse(text.isEmpty, "\(locale): \(key)")
            }
        }
    }

    func testCameraAndMicrophonePermissionsAreLocalized() throws {
        for locale in locales {
            let bundle = try localizedBundle(locale)
            for key in ["NSCameraUsageDescription", "NSMicrophoneUsageDescription"] {
                let text = bundle.localizedString(forKey: key, value: "__missing__", table: "InfoPlist")
                XCTAssertNotEqual(text, "__missing__", "\(locale): \(key)")
                XCTAssertTrue(text.contains("GradeLab"))
            }
        }
    }

    func testReorderedCameraArgumentsKeepTheirTypesAndValues() throws {
        let bundle = try localizedBundle("ja")
        let channel = bundle.localizedString(forKey: "Channel %lld: %@", value: nil, table: nil)
        XCTAssertEqual(String(format: channel, arguments: [Int64(2), "−12 dBFS"]), "チャンネル2：−12 dBFS")
        let remaining = bundle.localizedString(forKey: "≈ %lldh %lldm", value: nil, table: nil)
        XCTAssertEqual(String(format: remaining, arguments: [Int64(1), Int64(20)]), "約1時間20分")
        XCTAssertEqual(bundle.localizedString(forKey: "camera.shutter.speed", value: nil, table: nil), "速度")
    }

    private func localizedBundle(_ locale: String) throws -> Bundle {
        let url = try XCTUnwrap(Bundle.main.url(forResource: locale, withExtension: "lproj"))
        return try XCTUnwrap(Bundle(url: url))
    }
}

